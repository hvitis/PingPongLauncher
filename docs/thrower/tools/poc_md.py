#!/usr/bin/env python3
"""Generate docs/POC.md, the proof-of-concept test plan, from web/data/phases.json.

The same file drives the web viewer's POC tab and the A1 print zips, so the
three never disagree. Run:  python3 tools/poc_md.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
spec = json.loads((ROOT / "web" / "data" / "phases.json").read_text())
bom = json.loads((ROOT / "web" / "data" / "bom.json").read_text())
items = {it["id"]: it for g in bom["groups"] for it in g["items"]}
a1 = spec["a1"]


def cost(ph):
    return sum(q * items[i]["price"] for i, q in ph["buy"])


def zl(x):                       # round half up, as the viewer does
    return int(x + 0.5)


out = [
    "# Proof-of-concept test phases",
    "",
    "<!-- generated by tools/poc_md.py from web/data/phases.json: edit that file, not this one -->",
    "",
    spec["note"],
    "",
    "| Phase | Answers | Print | Buy ≈ |",
    "|---|---|---:|---:|",
]
for ph in spec["phases"]:
    out.append(f"| **{ph['id']} · {ph['name']}** | {ph['question']} | {sum(q for _, q in ph['print'])} parts | {zl(cost(ph))} zł |")
out += [
    f"| | **All {len(spec['phases'])} phases** | | **{zl(sum(cost(ph) for ph in spec['phases']))} zł** |",
    "",
    f"**Print settings for every phase:** {a1['printer']}, {a1['nozzle']} mm nozzle, {a1['layer']} mm layers, "
    f"{a1['infill']} % {a1['pattern']} infill, {a1['filament']}, supports {a1['supports']}. {a1['note']} "
    "`python3 docs/thrower/tools/build.py a1` writes one Bambu Studio project per part to `print/a1/` and a zip per phase "
    "(`print/a1/phase1.zip` …). The web viewer (`make serve`, POC tab) has the same downloads and plays each build step in 3D.",
    "",
    "**Firmware:** set `PHASE` in `firmware/config.py` to the phase you are testing. The firmware only drives what is "
    "fitted (no servo pulses on empty headers, no reads of floating button pins), the phone page hides the missing "
    f"controls, and before phase {spec['phases'][-1]['id']} the Pico's on-board LED shows READY.",
    "",
]
for ph in spec["phases"]:
    out += [f"## Phase {ph['id']} · {ph['name']}", "", f"**Question:** {ph['question']}", "", ph["summary"], ""]
    out += ["### Print", "", f"Download: `print/a1/phase{ph['id']}.zip`", "", "| Part | Qty |", "|---|---:|"]
    out += [f"| `{p}` | {q} |" for p, q in ph["print"]]
    out += ["", "### Buy", "", ph["start"], "", "| # | Item | Qty | ≈ zł |", "|---|---|---:|---:|"]
    out += [f"| {i} | {items[i]['name']} | {q} | {zl(q * items[i]['price'])} |" for i, q in ph["buy"]]
    out += [f"| | **Phase {ph['id']}** | | **{zl(cost(ph))}** |", "", "Tools and supplies:", ""]
    out += [f"- {t}" for t in ph["tools"]]
    out += ["", "### Wiring", "", f"![Phase {ph['id']} wiring](wiring_p{ph['id']}.svg)", ""]
    if ph.get("wiring3d"):
        out += [f"Every cable in 3D, step by step: [the Wiring view](../../index.html?launcher=thrower#thrower-workbench) (open it through `make serve`).", ""]
    out += [f"- {t}" for t in ph["wiring"]]
    out += ["", f"Firmware: `PHASE = {ph['firmware']}`.", "", "### Build", ""]
    out += [f"{n}. **{st['title']}.** {st['text']}" for n, st in enumerate(ph["steps"], 1)]
    out += ["", "### Tests", ""]
    out += [f"- [ ] **{what}.** {passes}" for what, passes in ph["tests"]]
    out += ["", f"**Before the next phase:** {ph['exit']}", ""]

dst = ROOT / "docs" / "POC.md"
dst.write_text("\n".join(out))
print(f"wrote {dst.relative_to(ROOT)}")
